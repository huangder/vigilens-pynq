"""Generate the C model header from face68_3d.json (single source, no hand copy).

The JSON stays the authoritative asset (it records provenance, frames used and
per-point residuals); this script only serialises the 68x3 numbers for the PS
build. Re-run it whenever the JSON changes.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=Path(__file__).with_name("face68_3d.json"))
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("face68_3d.h"))
    parser.add_argument('--symbol',default='VG_FACE68_MODEL')
    parser.add_argument('--guard',default='VG_FACE68_3D_H')
    args = parser.parse_args(argv)
    payload = json.loads(args.model.read_text(encoding="utf-8"))
    if not all(re.fullmatch('[A-Z_][A-Z_0-9]*',s) for s in (args.symbol,args.guard)):
        raise SystemExit('invalid C model identifier')
    points = payload["points_68"]
    if len(points) != 68 or any(len(p) != 3 for p in points):
        raise SystemExit("face68_3d.json must contain 68 xyz points")
    digest = hashlib.sha256(args.model.read_bytes()).hexdigest()
    lines = [
        "/* GENERATED by gen_face68_header.py from face68_3d.json; do not edit.",
        " * " + payload["header"],
        " * " + payload["note"],
        f" * source sha256: {digest}",
        f" * frames_used: {payload['frames_used']}",
        " */",
        f"#ifndef {args.guard}",
        f"#define {args.guard}",
        f"static const double {args.symbol}[68][3] = {{",
    ]
    for x, y, z in points:
        lines.append(f"    {{{x:.6f}, {y:.6f}, {z:.6f}}},")
    lines += ["};", "#endif", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"output": str(args.output), "sha256": digest, "points": 68}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
