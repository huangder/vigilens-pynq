// =============================================================================
//  motion_quality_cap.h —— motion_quality 片内"上一帧"缓存的**容量唯一来源**
// -----------------------------------------------------------------------------
//  项目：知倦 / VigiLens（AMD 3.3 自主选题初级组）—— C 线（FPGA/HLS）
//
//  为什么单独抽一个头文件：
//    这个容量是**编译期常量**（决定 BRAM 占用），而工作尺寸 width/height 是**运行时**由 PS 给的。
//    两者一旦不匹配就是"静默错"：
//      · csim 的 C 数组不设边界 ⇒ 越界写到相邻内存（可能看起来还能 PASS）；
//      · RTL 里 ram 只有这么大 ⇒ 越界地址读回 X、写被丢弃。
//    所以 IP（src）与测试台（sim/tb）**必须读同一份定义**，否则两边口径会漂。
//    写法与 `fir_coeffs_q15.h`（系数唯一来源，IP 与 tb 共用）一致：
//      src  ：  #include "motion_quality_cap.h"
//      tb   ：  #include "../src/motion_quality_cap.h"
//
//  📌 容量怎么定的（v1.5 测量口径档位化，三档工作尺寸都在这张表里）：
//
//    | 档位        | 抽取比 | 灰度工作尺寸 | 像素数    |
//    |---|---|---|---|
//    | 640×480     | 3/5    | 384×288      | 110592   |
//    | 1280×720    | 3/8    | 480×270      | 129600   |
//    | 1920×1080   | 1/4    | 480×270      | 129600   |
//    | **备用**    | ——     | 640×480      | 307200   | ← 不选：跨到 2^19 ⇒ 256 BRAM18（91%）
//
//  取最大档 **480×270 = 129600**。它 ≤ 2^17 = 131072，所以 HLS 按 2 的幂地址空间分配时
//  仍然只吃 **64 个 BRAM18 = xc7z020 的 23%**（与旧的 384×288 同价）。
//  ⚠️ 这就是"台阶式 BRAM"规律的应用：跨过 2 的幂就翻倍，贴着台阶挑最划算。
//     三组对照实验（320×240→64、512×512→128、640×480→256）见
//     `fpga/report/c4_rgb2gray_motion_quality_v1.md` 第 5 节。
//
//  ⚠️ 2026-10-01 修正记录（BUG-033）：原实现把容量写死成 384×288 = 110592，
//     **只覆盖 640×480 档**；v1.5 的 480×270 = 129600 会越界 19008 字节。
//     证据：`fpga/report/...`（480×270 全尺寸 csim 编译完成后 **>9 分钟零输出**，
//     而同尺寸 cosim 在旧容量下... 见报告；修后秒级通过）。
// =============================================================================

#ifndef MOTION_QUALITY_CAP_H
#define MOTION_QUALITY_CAP_H

// 工作尺寸上界（灰度像素）。IP 的片内缓存按它开，宽高由 PS 在运行时给。
#define MOTION_MAX_W 480
#define MOTION_MAX_H 270

// 片内缓存容量（像素数）。129600 ≤ 2^17 ⇒ 64 个 BRAM18。
#define MOTION_MAX_PIXELS (MOTION_MAX_W * MOTION_MAX_H)

#endif  // MOTION_QUALITY_CAP_H
